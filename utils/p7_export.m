function folder = p7_export(result,root)
% P7_EXPORT Keep configuration, raw data and failures with every run.
folder=fullfile(root,'results',char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
if ~isfolder(folder), mkdir(folder); end
save(fullfile(folder,'run.mat'),'result');
L=result.log; n=result.metrics.samples;
if n>0
    T=table(L.t(1:n)',L.qTrue(1,1:n)',L.qTrue(2,1:n)',L.qTrue(3,1:n)', ...
        L.qHat(1,1:n)',L.qHat(2,1:n)',L.qHat(3,1:n)', ...
        L.reference(1,1:n)',L.reference(2,1:n)',L.reference(3,1:n)', ...
        L.omega(1:n)',L.omegaRequested(1:n)',L.progress(1:n)',L.solveTime(1:n)',L.ok(1:n)', ...
        'VariableNames',{'time','trueX','trueY','trueTheta','estimatedX','estimatedY','estimatedTheta', ...
        'referenceX','referenceY','referenceTheta','omegaApplied','omegaRequested','progress','solveSeconds','solverOK'});
    writetable(T,fullfile(folder,'timeseries.csv'));
end
fid=fopen(fullfile(folder,'summary.txt'),'w','n','UTF-8');
clean=onCleanup(@() fclose(fid));
fprintf(fid,'Engine: %s\nController: %s\nReference: %s\nStatus: %s\nMessage: %s\n', ...
    result.engine,result.config.controller,result.config.referenceMode,result.status,result.message);
fprintf(fid,'Position RMSE: %.6g m\nHeading RMSE: %.6g rad\nEstimation RMSE: %.6g m\n', ...
    result.metrics.positionRMSE,result.metrics.headingRMSE,result.metrics.estimationRMSE);
fprintf(fid,'Mean solve time: %.6g s\nMax solve time: %.6g s\nTracking criterion met: %d\n', ...
    result.metrics.meanSolveTime,result.metrics.maxSolveTime,result.metrics.trackingSuccess);
fprintf(fid,'Convergence time: %.6g s\nPeak turn rate: %.6g rad/s\nFailure count: %d\n', ...
    result.metrics.convergenceTime,result.metrics.peakTurnRate,result.metrics.failureCount);
end
